-- Run this file in Supabase Dashboard > SQL Editor.
create extension if not exists pgcrypto;

create table if not exists public.projects (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  slug text unique,
  description text not null,
  tech_stack text[] not null default '{}',
  image_url text,
  github_url text,
  live_url text,
  featured boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 100),
  email text not null check (char_length(email) between 3 and 254),
  subject text check (subject is null or char_length(subject) <= 160),
  message text not null check (char_length(message) between 1 and 5000),
  created_at timestamptz not null default now()
);

alter table public.projects enable row level security;
alter table public.contact_messages enable row level security;

-- Public visitors can read published portfolio projects.
drop policy if exists "Public can view projects" on public.projects;
create policy "Public can view projects"
on public.projects for select to anon, authenticated
using (true);

-- Only the intended admin account can change project rows.
-- Replace the email with the exact email you create in Supabase Auth.
-- Keep it lowercase and quote the full email.
drop policy if exists "Portfolio admin can insert projects" on public.projects;
create policy "Portfolio admin can insert projects"
on public.projects for insert to authenticated
with check ((select auth.jwt() ->> 'email') = 'YOUR_ADMIN_EMAIL@example.com');

drop policy if exists "Portfolio admin can update projects" on public.projects;
create policy "Portfolio admin can update projects"
on public.projects for update to authenticated
using ((select auth.jwt() ->> 'email') = 'YOUR_ADMIN_EMAIL@example.com')
with check ((select auth.jwt() ->> 'email') = 'YOUR_ADMIN_EMAIL@example.com');

drop policy if exists "Portfolio admin can delete projects" on public.projects;
create policy "Portfolio admin can delete projects"
on public.projects for delete to authenticated
using ((select auth.jwt() ->> 'email') = 'YOUR_ADMIN_EMAIL@example.com');

-- Public contact form: insert-only. No public read/update/delete.
drop policy if exists "Anyone can submit contact messages" on public.contact_messages;
create policy "Anyone can submit contact messages"
on public.contact_messages for insert to anon, authenticated
with check (
  char_length(trim(name)) > 0
  and char_length(trim(email)) >= 3
  and char_length(trim(message)) > 0
);

